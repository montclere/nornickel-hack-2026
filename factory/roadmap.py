# -*- coding: utf-8 -*-
"""Дорожная карта эксперимента: гипотеза → этапы «лаборатория → пилот → внедрение».
ДЕТЕРМИНИРОВАННО, шаблоном — как rules.py: читаемая таблица, эксперт может править.

Закрывает критерий ТЗ «дорожная карта эксперимента»: одиночный протокол проверки
(`Hypothesis.experiment`) отвечает на «что проверить», а дорожная карта — на «как
довести до цеха, не рискуя производством»: нельзя перестраивать работающую фабрику
без лабораторного подтверждения и пилота на одной секции. У каждого этапа — явный
КРИТЕРИЙ ПЕРЕХОДА (го/стоп): не выполнен → дальше не идём, гипотеза закрывается
дёшево на ранней стадии.

Первые два этапа зависят от семейства вмешательства (лабораторная методика и форма
пилота у измельчения и у флотации разные), третий — общий. Незнакомое семейство
(новые правила, ветка Б) получает универсальный, но честный шаблон.
"""
from __future__ import annotations

# семейство → (лабораторная методика, форма пилота на одной секции)
_BY_FAMILY = {
    "раскрытие / измельчение": (
        "отобрать представительную пробу хвостов класса {cls}; кинетика доизмельчения "
        "навески до 2–3 целевых крупностей + флотация продуктов помола; построить "
        "кривую «крупность → извлечение {el}»",
        "выделенный цикл доизмельчения (байпас на одну мельницу / опытный гидроциклон) "
        "на ОДНОЙ секции, 2–4 недели, контроль гранулометрии и баланса {el}",
    ),
    "извлечение шламов / классификация": (
        "ситовый анализ пробы хвостов; лабораторное грохочение/классификация узкого "
        "класса {cls} с последующей флотацией подрешётного продукта; замер извлечения {el}",
        "опытный аппарат (тонкий грохот / сменные насадки гидроциклона) на ОДНОЙ "
        "секции, 2–4 недели, контроль выхода класса {cls} и качества концентрата",
    ),
    "доизвлечение флотацией": (
        "кинетика флотации пробы отвальных хвостов (время до плато извлечения {el}); "
        "оценить, докуда дофлотируется класс {cls} при увеличенном времени/перечистке",
        "перераспределение фронта флотации / контрольная флотация на ОДНОЙ линии "
        "существующим оборудованием, 2–4 недели, товарный баланс {el} до/после",
    ),
}
_GENERIC = (
    "лабораторная проверка «{intervention}» на представительной пробе хвостов класса "
    "{cls}: замер извлечения {el} до/после при контролируемых условиях",
    "опытно-промышленные испытания «{intervention}» на ОДНОЙ секции/линии, 2–4 недели, "
    "контроль баланса {el} и смежных показателей",
)


def build_roadmap(family: str, intervention: str, size_class: str, element: str) -> list:
    """Три этапа с критериями перехода. Возвращает [{stage,name,actions,success}]."""
    lab, pilot = _BY_FAMILY.get(family, _GENERIC)
    f = lambda s: s.format(cls=size_class, el=element, intervention=intervention)
    return [
        {"stage": 1, "name": "Лабораторный тест",
         "actions": f(lab),
         "success": f("прирост извлечения {el} из класса {cls} против базовой пробы "
                      "статистически значим (порог согласовать с технологом, "
                      "ориентир ≥2 абс.%) — иначе гипотеза закрывается на лаборатории")},
        {"stage": 2, "name": "Пилот на одной секции",
         "actions": f(pilot),
         "success": f("эффект воспроизводится в потоке: прирост извлечения {el} "
                      "подтверждён товарным балансом секции, качество концентрата и "
                      "смежные показатели не деградировали — иначе возврат/доработка")},
        {"stage": 3, "name": "Промышленное внедрение",
         "actions": f("тираж решения на все секции; актуализация технологического "
                      "регламента и карт контроля; обучение персонала"),
         "success": f("устойчивое снижение потерь {el} в классе {cls} в МЕСЯЧНОМ "
                      "балансе фабрики относительно базового периода")},
    ]
