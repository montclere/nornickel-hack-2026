# -*- coding: utf-8 -*-
"""Генерация DEVELOPER_GUIDE.pdf — минималистичный гайд по системе (reportlab).

Запуск:  uv run python -m factory.docs.build_guide
Шрифты:  DejaVuSans (кириллица) из /usr/share/fonts/truetype/dejavu/
"""
from __future__ import annotations

import os

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (BaseDocTemplate, Frame, HRFlowable, PageTemplate,
                                Paragraph, Spacer, Table, TableStyle)

FONT_DIR = "/usr/share/fonts/truetype/dejavu"
INK = colors.HexColor("#12303f")
TEAL = colors.HexColor("#0f9c95")
BLUE = colors.HexColor("#1f6fd0")
MUTED = colors.HexColor("#6b8593")
LINE = colors.HexColor("#dce6ec")
BG_CODE = colors.HexColor("#f4f8fb")


def _fonts():
    pdfmetrics.registerFont(TTFont("DJ", f"{FONT_DIR}/DejaVuSans.ttf"))
    pdfmetrics.registerFont(TTFont("DJ-B", f"{FONT_DIR}/DejaVuSans-Bold.ttf"))
    pdfmetrics.registerFont(TTFont("DJ-M", f"{FONT_DIR}/DejaVuSansMono.ttf"))


def _styles():
    base = dict(fontName="DJ", textColor=INK, leading=13.5, fontSize=9.3, alignment=TA_LEFT)
    return {
        "title": ParagraphStyle("t", **{**base, "fontName": "DJ-B", "fontSize": 21,
                                        "leading": 24, "textColor": INK, "spaceAfter": 2}),
        "sub": ParagraphStyle("s", **{**base, "fontSize": 10, "textColor": MUTED,
                                      "spaceAfter": 10}),
        "h2": ParagraphStyle("h2", **{**base, "fontName": "DJ-B", "fontSize": 13,
                                      "textColor": TEAL, "spaceBefore": 14, "spaceAfter": 3}),
        "h3": ParagraphStyle("h3", **{**base, "fontName": "DJ-B", "fontSize": 10.5,
                                      "textColor": BLUE, "spaceBefore": 8, "spaceAfter": 2}),
        "body": ParagraphStyle("b", **{**base, "spaceAfter": 5}),
        "li": ParagraphStyle("li", **{**base, "leftIndent": 12, "spaceAfter": 3,
                                      "bulletIndent": 2}),
        "code": ParagraphStyle("c", **{**base, "fontName": "DJ-M", "fontSize": 8,
                                       "leading": 11, "backColor": BG_CODE,
                                       "borderPadding": 6, "textColor": INK, "spaceAfter": 6}),
        "small": ParagraphStyle("sm", **{**base, "fontSize": 8, "textColor": MUTED}),
    }


def build(path="DEVELOPER_GUIDE.pdf"):
    _fonts()
    st = _styles()
    story = []

    def P(t, s="body"): story.append(Paragraph(t, st[s]))
    def H2(t): story.append(HRFlowable(width="100%", thickness=0.6, color=LINE,
                                       spaceBefore=6, spaceAfter=2)); P(t, "h2")
    def H3(t): P(t, "h3")
    def LI(items): [story.append(Paragraph("• " + i, st["li"])) for i in items]
    def CODE(t): story.append(Paragraph(t.replace("\n", "<br/>").replace(" ", "&nbsp;"), st["code"]))
    def SP(h=4): story.append(Spacer(1, h))

    def TBL(rows, widths):
        t = Table(rows, colWidths=widths, style=TableStyle([
            ("FONT", (0, 0), (-1, -1), "DJ", 8), ("FONT", (0, 0), (-1, 0), "DJ-B", 8),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("BACKGROUND", (0, 0), (-1, 0), TEAL),
            ("TEXTCOLOR", (0, 1), (-1, -1), INK),
            ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f7fbfc")]),
        ]))
        story.append(t); SP(6)

    # ─────────────────────────── ТИТУЛ ───────────────────────────
    P("Фабрика гипотез", "title")
    P("Гайд разработчика · детерминированное ядро анализа хвостов обогащения", "sub")
    P("Система по Excel-отчёту о хвостах строит граф знаний, ставит диагноз (где и в "
      "какой минеральной форме теряется извлекаемый металл) и выдаёт ранжированные "
      "проверяемые инженерные гипотезы. <b>Вся логика детерминирована и заземлена в ячейки "
      "отчёта; LLM применяется только для оформления текста и ни на что не влияет по "
      "существу.</b>")

    # ─────────────────────────── ПРИНЦИП ───────────────────────────
    H2("1. Ключевой принцип")
    LI(["<b>Детерминизм.</b> Тот же файл → тот же граф, те же гипотезы, те же числа. "
        "Ни ML, ни эмбеддингов, ни LLM в логике.",
        "<b>Grounding.</b> Каждое число прослеживается до ячейки Excel (напр. E205). "
        "«Цитата» — это координата, а не текст → галлюцинировать нечем.",
        "<b>Прозрачность.</b> Диагноз — по читаемой таблице правил; метрики — арифметика. "
        "Эксперт может прочитать и отредактировать каждое правило.",
        "<b>LLM снаружи, не внутри.</b> Модель — опциональный слой оформления/советов над "
        "ядром, не в пути рассуждения."])

    # ─────────────────────────── ПОТОК ДАННЫХ ───────────────────────────
    H2("2. Поток данных")
    CODE(
        "Excel хвостов\n"
        "  │  reader.py     openpyxl + поиск по подписям-якорям + валидация\n"
        "  ▼\n"
        "TailingsProfile   классы крупности × минеральные формы × тонны (+ провенанс-ячейка)\n"
        "  ├─► knowledge.py   networkx: узлы Элемент/Класс/Форма → граф (для SVG)\n"
        "  ├─► analysis.py    кривая раскрытия, обрыв, trade-off, форм-разбивка\n"
        "  └─► generator.py + metrics.py + rules.py\n"
        "        rules:    (доминирующая форма + крупность) → семейство вмешательства\n"
        "        metrics:  impact/addressability/clarity/feasibility/confidence → priority\n"
        "        generator: шаблон ЕСЛИ/ТО/ПОТОМУ ЧТО + заземление до ячейки\n"
        "  ▼\n"
        "Hypotheses (ранжированы)\n"
        "  ├─► [опц.] llm.py Phraser — только полировка текста (Yandex), анти-галлюцинация\n"
        "  ▼\n"
        "report.py → HTML (граф + кривая + формы + карточки) + glossary.py\n"
        "evaluate/benchmark.py → сверка семейств с эталоном Гипотезы*.docx")

    H2("3. Модули: вход / выход / алгоритм")
    TBL([
        ["Модуль", "Вход → Выход", "Алгоритм"],
        ["reader.py", "xlsx → TailingsProfile", "поиск строк-якорей в колонке B, чтение "
         "ролей колонок D/E/F/G, канонизация классов, валидация баланса"],
        ["knowledge.py", "Profile → networkx-граф", "узлы Элемент/Класс/Форма, рёбра с "
         "тоннажем; только для визуализации"],
        ["analysis.py", "Profile → аналитика", "арифметика долей форм по классам; поиск "
         "«обрыва раскрытия»; правило-детектор trade-off"],
        ["rules.py", "форма+класс → диагноз", "таблица правил обогащения (if/elif)"],
        ["metrics.py", "Profile+диагнозы → метрики", "безразмерная арифметика долей и "
         "произведений"],
        ["generator.py", "Profile → Hypotheses", "шаблонная сборка карточки + заземление"],
        ["llm.py", "Hypotheses → Hypotheses", "Yandex chat, только перефраз; анти-"
         "галлюцинация по числам (опц.)"],
        ["report/glossary", "всё → HTML", "строковые f-шаблоны + SVG вручную"],
        ["evaluate/benchmark", "гипотезы+docx → %", "классификация в 5 семейств по "
         "ключевым словам, coverage"],
    ], [70, 175, 250])

    # ─────────────────────────── ЛОГИКА ПОШАГОВО ───────────────────────────
    H2("4. Логика по шагам")

    H3("4.1 reader.py — чтение (детерминированный парсинг)")
    P("Читает лист openpyxl в словарь ячеек. Находит ПОСЛЕДНЮЮ таблицу с подписью "
      "«Класс крупности» (секция «отвальные общие» = итоговые потери). Роли колонок "
      "зашиты: C=доля класса, D=%Ni, E=т Ni, F=%Cu, G=т Cu. Далее блоки минералогии по "
      "классам («+125 мкм» … «Раскрытый Pnt/Cp» … «Итого»). Класс канонизируется "
      "удалением пробелов («-71 + 45 мкм» → «-71+45»). Битые формулы (#REF!) → None.")
    P("<b>Извлекаемость форм</b> (из инструкции «Как читать отчёт»): для Ni — раскрытый и "
      "закрытый Pnt/Cp + миллерит; для Cu — раскрытый и закрытый Pnt/Cp. Силикаты/"
      "валлериит, пирит, примесь в пирротине — физически не извлекаемы.")
    P("<b>Валидация:</b> число классов ≈6; сумма тонн по формам ≈ итогу класса (±25%); "
      "извлекаемое ≤ всего металла класса. Нарушение → предупреждение (парс мог сбиться).")

    H3("4.2 analysis.py — научная аналитика")
    LI(["<b>Кривая раскрытия:</b> доли раскрытого/закрытого/извлекаемого Ni по классам. "
        "Показывает физику liberation-by-size (закрытый Pnt падает с уменьшением частиц).",
        "<b>Обрыв раскрытия:</b> самый крупный класс, где закрытого больше раскрытого → "
        "граница, ниже которой измельчение раскрывает минерал.",
        "<b>Trade-off:</b> измельчение крупных классов увеличивает -10 шламы (где уже "
        "теряется раскрытый Ni) — конфликт, подтверждаемый данными.",
        "<b>Форм-разбивка:</b> куда физически уходит Ni; отделяет извлекаемое от "
        "физически потерянного (честный потолок)."])

    H3("4.3 rules.py + metrics.py — диагноз и метрики")
    P("Диагноз = функция от (доминирующая извлекаемая форма, крупность): закрытый → "
      "недораскрытие (измельчение); раскрытый+тонкий → шламы (грохочение/классификация); "
      "раскрытый+крупный → недофлотация. Каждому семейству — список вмешательств и "
      "источник.")
    P("Метрики (все 0..1, безразмерные, без денег):")
    TBL([
        ["Метрика", "Формула", "Смысл"],
        ["impact", "извл_тонны_класса / Σ извл_тонны", "масштаб потери (ведёт ранг)"],
        ["addressability", "извл_тонны / все_тонны_класса", "«излечимость»"],
        ["clarity", "тонны_главной_формы / извл_тонны", "ясность механизма (научная)"],
        ["feasibility", "1.0 без оборуд. / 0.6 с оборуд.", "реализуемость (из правила)"],
        ["confidence", "полнота данных 0.3/0.6/1.0", "достоверность парса"],
        ["priority", "impact·(0.5+0.5·adr)·feas·conf", "итоговый ранг"],
    ], [80, 200, 215])

    H3("4.4 generator / llm / report")
    P("generator собирает карточку ЕСЛИ/ТО/ПОТОМУ ЧТО шаблоном из детерминированных полей "
      "и прикрепляет заземление (ячейки). llm.Phraser (опц., --polish) переписывает текст "
      "глаже, но отклоняется, если в правке появились числа, которых не было (анти-"
      "галлюцинация). report/glossary рисуют самодостаточный HTML (граф и кривая — SVG "
      "вручную).")

    H2("5. Научные подходы")
    LI(["<b>Liberation-by-size</b> — классика обогащения: степень раскрытия минерала "
        "зависит от крупности; из данных строим кривую и целевую крупность помола.",
        "<b>Минералого-технологическая диагностика</b> — потери разносятся по формам; "
        "вмешательство определяется формой (сросток → измельчение; шлам → классификация).",
        "<b>Mass-balance валидация</b> — контроль сумм («Итого проверка» ≈100%) как "
        "детектор ошибок парса.",
        "<b>Многокритериальность</b> — явные trade-off вместо одной «серебряной пули»."])

    H2("6. Плюсы")
    LI(["Детерминизм и воспроизводимость — аудируемо, защищаемо перед промышленным "
        "заказчиком, который не доверяет чёрным ящикам.",
        "Grounding до ячейки; «цитата» подделать нельзя.",
        "Скорость: полный проход ~0.03 c; не нужны сеть/ключи/GPU для ядра.",
        "Прозрачные правила и метрики — эксперт правит конфиг, не код.",
        "Честность: отделяем извлекаемое от физически потерянного; показываем trade-off.",
        "Family-coverage эталона 85% по 4 фабрикам (диагноз попадает в категории инженеров)."])

    H2("7. Минусы, узкие места, хардкод, особенности")
    LI(["<b>Хрупкость формата (главное).</b> reader зависит от конкретных якорей-подписей, "
        "ролей колонок D/E/F/G и имён классов. Сдвиг колонок / другой формат / не-xlsx → "
        "парс ломается или (хуже) молча указывает не на ту ячейку. Смягчено валидацией, "
        "но не устранено. Фикс: вынести формат в schema.json (сменный адаптер).",
        "<b>Доменная жёсткость.</b> Работает только для флотации Cu-Ni хвостов; другой "
        "материал/процесс требует замены reader+rules. Универсальны лишь граф/метрики/отчёт.",
        "<b>Хардкод правил и извлекаемых форм.</b> Таблица диагнозов и список извлекаемых "
        "минералов написаны вручную (хоть и инспектируемо). Это доменное знание, не "
        "выведенное из данных.",
        "<b>Слабый eval.</b> Family-coverage сравнивает 5 грубых категорий по ключевым "
        "словам → легко попасть; это проверка вменяемости, не доказательство точного "
        "воспроизведения. Списки ключевых слов — ручные.",
        "<b>Граф — не несущий.</b> Логика считается на таблицах, граф нужен только для "
        "картинки; networkx избыточен.",
        "<b>Анонимные элементы.</b> «Элемент 28/29» приняты за Ni/Cu по атомному номеру — "
        "допущение.",
        "<b>Секция отчёта.</b> Берём «отвальные общие» (последняя таблица); если структура "
        "секций изменится, выбор собьётся.",
        "<b>LLM почти не у дел.</b> Только --polish; по умолчанию не вызывается. Роль "
        "модели пока декоративна.",
        "<b>Приоритетные веса.</b> Коэффициенты (0.5+0.5·adr, пороги feasibility/confidence) "
        "подобраны экспертно, не откалиброваны на исходах."])

    H2("8. Идеи развития")
    H3("Детерминированные (усиливают ядро)")
    LI(["schema.json — вынести формат из reader → сменный адаптер под любой макет отчёта.",
        "Количественная модель раскрытия: подгонка liberation-vs-size → целевая крупность "
        "помола в микронах, а не «мельче класса X».",
        "Контрфактуал/чувствительность: «поднять извлечение раскрытого Pnt в -10 на N% → "
        "суммарные потери −M т».",
        "Кросс-фабричные системные паттерны: одна форма доминирует на всех фабриках → "
        "системная проблема цеха, а не локальная.",
        "Детектор аномалий: класс/фабрика, отклоняющиеся от нормы минералогии.",
        "Строгий eval: матч по конкретным вмешательствам или LLM-судья по смыслу."])
    H3("LLM/агент (над ядром, безопасно)")
    LI(["Vision → equipment.json: распознать PNG-схемы и списки оборудования → grounded "
        "feasibility вместо заглушки 0.6.",
        "LLM-критик: советы по каждой гипотезе (проверяемо? уже пробовали?), ранг не "
        "меняет; трасса рассуждений в HTML.",
        "Чат-объяснение поверх детерминированных результатов с цитатами до ячеек.",
        "LLM-однократный маппинг незнакомого формата → schema.json (человек подтверждает), "
        "дальше детерминизм."])

    P("Правило развития: гибкость и «понимание» кладём в адаптеры и надстройки; ядро "
      "(диагноз, метрики, заземление) остаётся детерминированным. Так система масштабируется, "
      "не превращаясь в чёрный ящик.", "small")

    # ─────────────────────────── СБОРКА ───────────────────────────
    frame = Frame(20 * mm, 16 * mm, A4[0] - 40 * mm, A4[1] - 32 * mm, id="f")

    def footer(cv, doc):
        cv.setFont("DJ", 7.5); cv.setFillColor(MUTED)
        cv.drawString(20 * mm, 10 * mm, "Фабрика гипотез · гайд разработчика")
        cv.drawRightString(A4[0] - 20 * mm, 10 * mm, f"стр. {doc.page}")

    doc = BaseDocTemplate(path, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                          topMargin=16 * mm, bottomMargin=16 * mm)
    doc.addPageTemplates([PageTemplate(id="main", frames=[frame], onPage=footer)])
    doc.build(story)
    return path


if __name__ == "__main__":
    out = build(os.path.join(os.getcwd(), "DEVELOPER_GUIDE.pdf"))
    print("PDF:", out)
